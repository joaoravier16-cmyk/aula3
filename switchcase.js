// switch case 
var escolhaMenu = 1

switch (escolhaMenu) {
    case 1 :
        console.log ("entrar")
             break // parar 
        case 2 :
            console.log ("cadastrar")
            break // parar
        case 3 :
            console.log ("editar")
            break // parar
        case 0 :
            console.log ("sair")
            break // parar
        default:
            console.log ("digita certo esse numero ai") 
}


